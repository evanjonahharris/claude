export function getOutcomeByLabel(displayLabel: string): OutcomeKey | undefined {
  return OUTREACH_OUTCOME_KEY.find(
    (o) => o.displayLabel.toLowerCase() === displayLabel.toLowerCase(),
  );
}

export function getOutcomeByCode(code: string): OutcomeKey | undefined {
  return OUTREACH_OUTCOME_KEY.find((o) => o.outcomeCode === code);
}

export function getOutcomesForMethod(method: string): OutcomeKey[] {
  // Text -> Call set; LinkedIn / In Person / Other -> Email set
  const resolved =
    method === 'Call' || method === 'Text'
      ? 'Call'
      : 'Email';
  return OUTREACH_OUTCOME_KEY.filter((o) => o.appliesToMethod === resolved);
}

export function getOutcomesByLeadStatus(leadStatus: string): OutcomeKey[] {
  return OUTREACH_OUTCOME_KEY.filter(
    (o) => o.defaultLeadStatus.toLowerCase() === leadStatus.toLowerCase(),
  );
}

